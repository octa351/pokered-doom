#!/usr/bin/env python3
# E1M1 (Doom shareware D_E1M1 notes, tools/e1m1.json) -> frame-quantized event streams for engine/doom/doom_music.asm.
# Stream = (value, frames_until_next_event) pairs; value $FE = nop (long gaps), $FF = loop marker (delta unused).
# Pulses/bass: value 0 = off, 24..96 = MIDI note. Drums: 1 kick, 2 snare, 3 tom, 4 hat.
import json, os, sys
d = os.path.dirname(os.path.abspath(__file__))
notes = json.load(open(os.path.join(d, 'e1m1.json')))
T, TPS, FPS = 13440, 140, 60
N = round(T * FPS / TPS)
frame = lambda t: round(t * FPS / TPS)

def mono(ch):
    a = [0] * T; starts = set()
    for c, s, dur, nt, v, _ in sorted(notes, key=lambda x: (x[1], x[3])):
        if c != ch: continue
        starts.add(s)
        for t in range(s, min(T, s + max(dur, 1))): a[t] = nt
    return a, starts
p1, s1 = mono(1); p2, s2 = mono(0); bs, s3 = mono(2)
p2 = [0 if p2[i] == p1[i] else p2[i] for i in range(T)]

def events(a, starts):   # tick-array -> {frame: value}, last tick in a frame wins
    ev = {}
    for t in range(T):
        if t == 0 or a[t] != a[t - 1] or t in starts: ev[frame(t)] = a[t]
    return ev
PRIO = {1: 0, 2: 1, 3: 2, 4: 3}
dr = {}
for c, s, dur, nt, v, _ in notes:
    if c != 15: continue
    ty = 1 if nt == 36 else 2 if nt in (38, 40) else 3 if nt in (41, 43, 45, 47, 50) else 4
    f = frame(s)
    if f not in dr or PRIO[ty] < PRIO[dr[f]]: dr[f] = ty

def stream(ev):
    fr = sorted(ev); out = []
    if fr[0] > 0: fr = [0] + fr; ev = dict(ev, **{0: 0xFE})
    for i, f in enumerate(fr):
        gap = (fr[i + 1] if i + 1 < len(fr) else N) - f
        out.append((ev[f], min(gap, 255))); gap -= 255
        while gap > 0: out.append((0xFE, min(gap, 255))); gap -= 255
    return out + [(0xFF, 0)]

def replay(st):   # per-frame value (None = nothing applied that frame), exactly as the driver does
    res = [None] * N; f = 0
    for v, dl in st[:-1]:
        if v != 0xFE: res[f] = v
        f += dl
    assert f == N and st[-1][0] == 0xFF
    return res

S = [stream(events(p1, s1)), stream(events(p2, s2)), stream(events(bs, s3)), stream(dr)]
for name, arr, st, st_starts in (('p1', p1, S[0], s1), ('p2', p2, S[1], s2), ('bs', bs, S[2], s3)):
    state, cur = [], 0
    for v in replay(st):
        cur = cur if v is None else v; state.append(cur)
    for f in range(N):   # state at frame f == tick array at the last tick that maps to <= f
        t = min(T - 1, -(-int((f + .5) * TPS * 100 / FPS) // 100) - 1)
        t = max(t, 0)
        while t + 1 < T and frame(t + 1) <= f: t += 1
        while frame(t) > f: t -= 1
        assert state[f] == arr[t], (name, f, state[f], arr[t])
rd = replay(S[3])
assert sum(1 for v in rd if v) == len(dr) and all(rd[f] == ty for f, ty in dr.items())

def freq(m): return max(0, min(2047, round(2048 - 131072 / (440 * 2 ** ((m - 69) / 12)))))
o = ['; generated by tools/gen_doom_music.py -- do not edit', f'DEF DOOM_SONG_FRAMES EQU {N}', '',
     'DoomFreqTable:  ; MIDI 24..96 -> GB 11-bit period (pulse: 131072/f; wave channel plays note+12)']
o += ['\tdw ' + ', '.join(f'${freq(m):03X}' for m in range(24 + i, min(97, 24 + i + 8))) for i in range(0, 73, 8)]
for lbl, st in zip(('Pulse1', 'Pulse2', 'Bass', 'Drums'), S):
    o += ['', f'DoomStream{lbl}:']
    o += ['\tdb ' + ', '.join(f'${v:02X}, {dl}' for v, dl in st[i:i + 8]) for i in range(0, len(st), 8)]
open(os.path.join(d, '..', 'gfx/doom/doom_music_data.asm'), 'w').write('\n'.join(o) + '\n')
print('frames', N, 'events', [len(s) for s in S], 'bytes', sum(len(s) for s in S) * 2 + 146)
